  await client.query("select set_config('test.member_role','admin',false)");
  const id='00000000-0000-4000-8000-000000000010';
  const first=await run(id,'monthly',3,'2028-01-31T18:00:00Z');
  assert.equal(first.rows[0].ids.length,3);
  const times=await client.query("select to_char(starts_at at time zone 'America/Chicago','YYYY-MM-DD HH24:MI') as date from event order by series_position");
  assert.deepEqual(times.rows.map(r=>r.date),['2028-01-31 12:00','2028-02-29 12:00','2028-03-31 12:00']);
  assert.deepEqual((await run(id,'monthly',3,'2028-01-31T18:00:00Z')).rows,first.rows);
  await assert.rejects(run(id,'monthly',3,'2028-01-31T18:00:00Z','Changed'),/different event details/);
  assert.equal((await client.query('select count(*)::int as n from personnel_audit')).rows[0].n,3);
  console.log('PASS monthly anchoring, retry identity, payload mismatch and audit count');
  const gap='00000000-0000-4000-8000-000000000011';
  await assert.rejects(run(gap,'daily',2,'2026-03-07T08:30:00Z'),/does not exist/);
  assert.equal((await client.query('select count(*)::int as n from event_series where id=$1',[gap])).rows[0].n,0);
  assert.equal((await client.query('select count(*)::int as n from event')).rows[0].n,3);
  console.log('PASS invalid daylight-saving occurrence rolls back the entire series');
  await run(gap,'daily',2,'2026-10-31T06:30:00Z');
