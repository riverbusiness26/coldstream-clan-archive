import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import EmbeddedPostgres from 'embedded-postgres';
const databaseDir = await mkdtemp(join(tmpdir(), 'coldstream-recurrence-test-'));
const server = createServer();
await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
const port = server.address().port;
await new Promise(resolve => server.close(resolve));
const db = new EmbeddedPostgres({ databaseDir, port, user:'postgres', password:'synthetic-test-only', persistent:false, onLog:()=>{}, onError:()=>{} });
let client;
try {
  await db.initialise(); await db.start(); client=db.getPgClient(); await client.connect();
  await client.query(`
    create role anon; create role authenticated; create role service_role;
    create table public.member(id uuid primary key);
    insert into public.member values('00000000-0000-4000-8000-000000000001');
    create function public.current_member_id() returns uuid language sql as $$ select '00000000-0000-4000-8000-000000000001'::uuid $$;
    create function public.current_member_role() returns text language sql as $$ select nullif(current_setting('test.member_role',true),'') $$;
    create table public.event(id uuid primary key default gen_random_uuid(), title text, body text, game text, starts_at timestamptz, duration_minutes int, created_by uuid, event_type text);
    create table public.personnel_audit(id bigserial primary key,actor_id uuid,action text,entity text,entity_id text,detail jsonb);
  `);
  const creation=readFileSync(new URL('../db/0049_optional_event_post.sql',import.meta.url),'utf8');
  await client.query(creation.slice(creation.indexOf('create or replace function create_website_event('),creation.indexOf('revoke all on function post_managed_event')));
  await client.query(readFileSync(new URL('../db/0055_recurring_events.sql',import.meta.url),'utf8'));
  const run = (id,kind,count,start,title='Synthetic event') => client.query('select public.create_recurring_website_events($1,$2,$3,$4,null,null,$5,90,$6) as ids',[id,kind,count,title,start,'linebattle']);
  await client.query("select set_config('test.member_role','admin',false)");
  const id='00000000-0000-4000-8000-000000000010';
  const first=await run(id,'monthly',3,'2028-01-31T18:00:00Z');
  assert.equal(first.rows[0].ids.length,3);
  const times=await client.query("select to_char(starts_at at time zone 'America/Chicago','YYYY-MM-DD HH24:MI') as date from event order by series_position");
  assert.deepEqual(times.rows.map(r=>r.date),['2028-01-31 12:00','2028-02-29 12:00','2028-03-31 12:00']);
  assert.deepEqual((await run(id,'monthly',3,'2028-01-31T18:00:00Z')).rows,first.rows);
  await assert.rejects(run(id,'monthly',3,'2028-01-31T18:00:00Z','Changed'),/different event details/);
  assert.equal((await client.query('select count(*)::int as n from personnel_audit')).rows[0].n,3);
  console.log('PASS monthly anchoring, retry identity, payload mismatch and audit count');
  const gap='00000000-0000-4000-8000-000000000011';
  await assert.rejects(run(gap,'daily',2,'2026-03-07T08:30:00Z'),/does not exist/);
  assert.equal((await client.query('select count(*)::int as n from event_series where id=$1',[gap])).rows[0].n,0);
  assert.equal((await client.query('select count(*)::int as n from event')).rows[0].n,3);
  console.log('PASS invalid daylight-saving occurrence rolls back the entire series');
  await run(gap,'daily',2,'2026-10-31T06:30:00Z');
  assert.equal((await client.query('select starts_at from event where series_id=$1 and series_position=2',[gap])).rows[0].starts_at.toISOString(),'2026-11-01T07:30:00.000Z');
  console.log('PASS ambiguous fall time uses second occurrence');
  await client.query("select set_config('test.member_role','member',false); set role authenticated");
  await assert.rejects(run('00000000-0000-4000-8000-000000000012','weekly',2,'2026-09-14T00:00:00Z'),/staff role required/);
  assert.equal((await client.query('select count(*)::int as n from event_series')).rows[0].n,0);
  await client.query("reset role; select set_config('test.member_role','moderator',false); set role authenticated");
  assert.equal((await run('00000000-0000-4000-8000-000000000012','weekly',2,'2026-03-07T01:00:00Z')).rows[0].ids.length,2);
  await client.query('reset role; set role anon');
  await assert.rejects(run('00000000-0000-4000-8000-000000000013','weekly',2,'2026-09-14T00:00:00Z'),/permission denied/);
  console.log('PASS member and anonymous rejection, staff-only series read, moderator creation');
  await client.query('reset role');
  await assert.rejects(run('00000000-0000-4000-8000-000000000013','weekly',105,'2026-09-14T00:00:00Z'),/104 occurrences/);
  console.log('PASS database count limit');
} finally {
  if(client) await client.end();
  await db.stop();
  if (!databaseDir.startsWith(join(tmpdir(),'coldstream-recurrence-test-'))) throw new Error('Unexpected test directory');
  await rm(databaseDir,{recursive:true,force:true});
}
