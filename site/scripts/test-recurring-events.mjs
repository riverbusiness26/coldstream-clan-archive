  const stopped=await client.query('select stop_repeating_event($1) n',[foreverId]);
  assert.ok(stopped.rows[0].n>0);
  assert.equal((await client.query('select deleted_at from event where series_id=$1 and series_position=1',[foreverId])).rows[0].deleted_at,null);
  assert.equal((await client.query('select stop_repeating_event($1) n',[foreverId])).rows[0].n,0);
